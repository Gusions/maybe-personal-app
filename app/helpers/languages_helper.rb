  def timezone_options
    ActiveSupport::TimeZone.all
      .sort_by { |tz| [ tz.utc_offset, tz.name ] }
      .map do |tz|
        name = tz.name.split(" - ").first.gsub(" (US & Canada)", "")
        [ "(#{tz.formatted_offset}) #{name}", tz.tzinfo.identifier ]
      end
  end
